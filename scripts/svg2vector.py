#!/usr/bin/env python3
"""Convert the 24-grid line icons (design/v3/icons-v2/svg) to VectorDrawables.

Usage: python3 scripts/svg2vector.py <svg dir> <res/drawable dir>
Handles path, rect (with rx) and circle; a shape with fill="currentColor" becomes a filled dot.
"""
import re
import sys
from pathlib import Path

RENAME = {"ic_device_other": "ic_device_unknown"}


def num(v):
    return f"{round(float(v), 3):g}"


def rect(a):
    x, y, w, h = (float(a[k]) for k in ("x", "y", "width", "height"))
    r = float(a.get("rx", 0))
    if r == 0:
        return f"M{num(x)} {num(y)}h{num(w)}v{num(h)}h{num(-w)}z"
    n = num
    return (
        f"M{n(x + r)} {n(y)}h{n(w - 2 * r)}a{n(r)} {n(r)} 0 0 1 {n(r)} {n(r)}v{n(h - 2 * r)}"
        f"a{n(r)} {n(r)} 0 0 1 {n(-r)} {n(r)}h{n(-(w - 2 * r))}a{n(r)} {n(r)} 0 0 1 {n(-r)} {n(-r)}"
        f"v{n(-(h - 2 * r))}a{n(r)} {n(r)} 0 0 1 {n(r)} {n(-r)}z"
    )


def circle(a):
    cx, cy, r = (float(a[k]) for k in ("cx", "cy", "r"))
    n = num
    return f"M{n(cx - r)} {n(cy)}a{n(r)} {n(r)} 0 1 0 {n(2 * r)} 0a{n(r)} {n(r)} 0 1 0 {n(-2 * r)} 0z"


def convert(svg):
    body = re.sub(r"<metadata>.*?</metadata>", "", svg, flags=re.S)
    body = re.sub(r"^.*?<svg[^>]*>", "", body, flags=re.S)
    out = []
    for tag, attrs in re.findall(r"<(path|rect|circle)\s([^>]*?)/>", body):
        a = dict(re.findall(r'([\w-]+)="([^"]*)"', attrs))
        data = a["d"] if tag == "path" else rect(a) if tag == "rect" else circle(a)
        if a.get("fill") == "currentColor":
            out.append(f'    <path\n        android:pathData="{data}"\n        android:fillColor="#FF000000" />')
        else:
            out.append(
                f'    <path\n        android:pathData="{data}"\n        android:strokeColor="#FF000000"\n'
                '        android:strokeWidth="1.5"\n        android:strokeLineCap="round"\n'
                '        android:strokeLineJoin="round" />'
            )
    return out


def main(src, dst):
    for svg in sorted(Path(src).glob("*.svg")):
        name = RENAME.get(svg.stem, svg.stem)
        paths = convert(svg.read_text(encoding="utf-8"))
        text = (
            '<?xml version="1.0" encoding="utf-8"?>\n'
            f"<!-- Generated by scripts/svg2vector.py from design/v3/icons-v2/svg/{svg.name}. Line icon, tint with Icon(tint=...). -->\n"
            '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
            '    android:width="24dp"\n    android:height="24dp"\n'
            '    android:viewportWidth="24"\n    android:viewportHeight="24">\n' + "\n".join(paths) + "\n</vector>\n"
        )
        Path(dst, f"{name}.xml").write_text(text, encoding="utf-8")
        print(name, len(paths))


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
